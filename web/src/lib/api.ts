import { supabase, supabaseAnonKey } from './supabase'
import type { BackgroundMedia, ExportJob, InstrumentalJob, Limits, SyncJob } from './types'

const API_URL = ((import.meta.env.VITE_API_URL as string | undefined) || 'http://localhost:8000').replace(/\/$/, '')

export class ApiError extends Error {
  code: string
  status: number
  constructor(code: string, status = 0) {
    super(code)
    this.code = code
    this.status = status
  }
}

async function accessToken(): Promise<string | null> {
  if (!supabase) return null
  const { data } = await supabase.auth.getSession()
  return data.session?.access_token ?? null
}

async function request<T>(path: string, init: RequestInit = {}): Promise<T> {
  const token = await accessToken()
  const headers = new Headers(init.headers)
  if (token) headers.set('Authorization', `Bearer ${token}`)
  if (init.body) headers.set('Content-Type', 'application/json')

  let resp: Response
  try {
    resp = await fetch(`${API_URL}${path}`, { ...init, headers })
  } catch {
    throw new ApiError(navigator.onLine ? 'api_unreachable' : 'network')
  }
  if (resp.status === 204) return undefined as T
  let body: unknown = null
  try {
    body = await resp.json()
  } catch {
    /* empty body */
  }
  if (!resp.ok) {
    const detail = (body as { detail?: unknown } | null)?.detail
    throw new ApiError(typeof detail === 'string' ? detail : 'generic', resp.status)
  }
  return body as T
}

export interface UploadInit {
  project_id: string
  audio_file_id: string
  upload_url: string
  content_type: string
}

export interface ProjectState {
  project_id: string
  status: string
  job_id: string | null
  duration_ms: number | null
  error_code: string | null
}

export type TextExportFormat = 'srt' | 'lrc' | 'ass'

export const api = {
  limits: () => request<Limits>('/limits'),
  initUpload: (file: File) =>
    request<UploadInit>('/uploads', {
      method: 'POST',
      body: JSON.stringify({ file_name: file.name, size_bytes: file.size, mime_type: file.type }),
    }),
  completeUpload: (projectId: string) => request<ProjectState>(`/uploads/${projectId}/complete`, { method: 'POST' }),
  retry: (projectId: string) => request<ProjectState>(`/projects/${projectId}/retry`, { method: 'POST' }),
  deleteProject: (projectId: string) => request<void>(`/projects/${projectId}`, { method: 'DELETE' }),
  createVideoExport: (projectId: string, aspect: string, resolution: number, audio: 'original' | 'instrumental' = 'original') =>
    request<ExportJob>(`/projects/${projectId}/exports`, {
      method: 'POST',
      body: JSON.stringify({ format: 'mp4', aspect, resolution, audio }),
    }),
  requestInstrumental: (projectId: string) => request<InstrumentalJob>(`/projects/${projectId}/instrumental`, { method: 'POST' }),
  cancelInstrumental: (projectId: string) => request<void>(`/projects/${projectId}/instrumental`, { method: 'DELETE' }),
  deleteExport: (exportId: string) => request<void>(`/exports/${exportId}`, { method: 'DELETE' }),
  initBackground: (projectId: string, file: File) =>
    request<{ media: BackgroundMedia; upload_url: string; content_type: string }>(`/projects/${projectId}/backgrounds`, {
      method: 'POST',
      body: JSON.stringify({ file_name: file.name, size_bytes: file.size }),
    }),
  completeBackground: (mediaId: string) => request<BackgroundMedia>(`/backgrounds/${mediaId}/complete`, { method: 'POST' }),
  deleteBackground: (mediaId: string) => request<void>(`/backgrounds/${mediaId}`, { method: 'DELETE' }),
  createSyncJob: (projectId: string, words: string[], windowStartMs: number, windowEndMs: number) =>
    request<SyncJob>(`/projects/${projectId}/sync-jobs`, {
      method: 'POST',
      body: JSON.stringify({ words, window_start_ms: windowStartMs, window_end_ms: windowEndMs }),
    }),
}

/** Download a subtitle file generated by the API and save it with the song's name. */
export async function downloadTextExport(projectId: string, format: TextExportFormat, title: string, aspect = '16:9') {
  const token = await accessToken()
  let resp: Response
  try {
    resp = await fetch(`${API_URL}/projects/${projectId}/export/${format}?aspect=${encodeURIComponent(aspect)}&resolution=1080`, {
      headers: token ? { Authorization: `Bearer ${token}` } : {},
    })
  } catch {
    throw new ApiError(navigator.onLine ? 'api_unreachable' : 'network')
  }
  if (!resp.ok) {
    let detail = 'generic'
    try {
      detail = (await resp.json()).detail ?? detail
    } catch {
      /* not json */
    }
    throw new ApiError(typeof detail === 'string' ? detail : 'generic', resp.status)
  }
  saveBlob(await resp.blob(), `${safeFileName(title)}.${format}`)
}

export function safeFileName(title: string): string {
  return title.replace(/[\\/:*?"<>|\r\n]+/g, ' ').trim().slice(0, 80) || 'karaoke'
}

export function saveBlob(blob: Blob, name: string) {
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = name
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 10000)
}

/**
 * Upload the file DIRECTLY to Supabase Storage using the one-time signed URL
 * issued by the API (the file never passes through our servers).
 * XHR is used instead of fetch because it reports upload progress.
 */
export function uploadToSignedUrl(
  url: string,
  file: File,
  contentType: string,
  onProgress: (fraction: number) => void,
  signal?: AbortSignal,
): Promise<void> {
  return new Promise((resolve, reject) => {
    const xhr = new XMLHttpRequest()
    xhr.open('PUT', url)
    xhr.setRequestHeader('Content-Type', contentType)
    xhr.setRequestHeader('x-upsert', 'false')
    if (supabaseAnonKey) xhr.setRequestHeader('apikey', supabaseAnonKey)
    xhr.upload.onprogress = (e) => {
      if (e.lengthComputable) onProgress(e.loaded / e.total)
    }
    xhr.onload = () => {
      if (xhr.status >= 200 && xhr.status < 300) {
        onProgress(1)
        resolve()
      } else {
        reject(new ApiError(xhr.status === 413 ? 'file_too_large' : 'upload_failed', xhr.status))
      }
    }
    xhr.onerror = () => reject(new ApiError(navigator.onLine ? 'upload_failed' : 'network'))
    xhr.onabort = () => reject(new ApiError('aborted'))
    signal?.addEventListener('abort', () => xhr.abort())
    xhr.send(file)
  })
}
