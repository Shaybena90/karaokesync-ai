#!/usr/bin/env python3
"""Generate Content/KanafData/Catalog/bases.json from OurAirports CSVs (public domain).

Usage: python3 tools/extract_bases.py --airports airports.csv --runways runways.csv --out bases.json
Get the CSVs from https://ourairports.com/data/ (or the GitHub mirror davidmegginson/ourairports-data).
Base names, Hebrew names and unit notes are curated below; coordinates/elevations/runways come
only from the dataset. Runway geometry is NOT survey-grade; taxiways/aprons/shelters are not
modelled (public layouts are not reproduced — the in-game representation is schematic).
"""
import argparse, csv, json

FT = 0.3048
BASES = [
    {"id": "ramon", "icao": "LLRM", "nameHe": "בסיס חיל האוויר רמון", "shortHe": "רמון", "nameEn": "Ramon Airbase",
     "units": [{"textHe": "טייסות F-16I סופה", "verification": "reported_unverified_this_session"}], "phase1": True},
    {"id": "nevatim", "icao": "LLNV", "nameHe": "בסיס חיל האוויר נבטים", "shortHe": "נבטים", "nameEn": "Nevatim Airbase",
     "units": [{"textHe": "טייסות F-35I אדיר (116, 140, 117)", "verification": "documented", "sources": ["src_armyrec_f35_48"]},
               {"textHe": "טייסת 122 (נחשון)", "verification": "documented", "sources": ["src_wiki_122sqn", "src_aviationist_oron"]}]},
    {"id": "hatzerim", "icao": "LLHB", "nameHe": "בסיס חיל האוויר חצרים", "shortHe": "חצרים", "nameEn": "Hatzerim Airbase",
     "units": [{"textHe": "טייסת 69 — F-15I רעם", "verification": "documented", "sources": ["src_twz_f15ia_rearm"]}]},
    {"id": "telnof", "icao": "LLEK", "nameHe": "בסיס חיל האוויר תל נוף", "shortHe": "תל נוף", "nameEn": "Tel Nof Airbase",
     "units": [{"textHe": "מטוסי F-15 בז", "verification": "reported_unverified_this_session"}]},
    {"id": "ramatdavid", "icao": "LLRD", "nameHe": "בסיס חיל האוויר רמת דוד", "shortHe": "רמת דוד", "nameEn": "Ramat David Airbase", "units": []},
    {"id": "hatzor", "icao": "LLHS", "nameHe": "בסיס חיל האוויר חצור", "shortHe": "חצור", "nameEn": "Hatzor Airbase", "units": []},
]


def f(x):
    return float(x) if x not in ("", None) else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--airports", required=True)
    ap.add_argument("--runways", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    apts = {r["ident"]: r for r in csv.DictReader(open(a.airports, encoding="utf-8"))}
    rws = {}
    for r in csv.DictReader(open(a.runways, encoding="utf-8")):
        rws.setdefault(r["airport_ident"], []).append(r)
    out = []
    for b in BASES:
        ap_ = apts[b["icao"]]
        elev = f(ap_["elevation_ft"])
        runways = []
        for r in rws.get(b["icao"], []):
            if r["closed"] == "1" or not r["le_latitude_deg"] or not r["he_latitude_deg"]:
                continue
            le_e = f(r["le_elevation_ft"]); he_e = f(r["he_elevation_ft"])
            runways.append({
                "id": f'{r["le_ident"]}/{r["he_ident"]}',
                "lengthM": round(f(r["length_ft"]) * FT, 1), "widthM": round(f(r["width_ft"]) * FT, 1),
                "surface": r["surface"], "lighted": r["lighted"] == "1",
                "ends": [
                    {"ident": r["le_ident"], "lat": f(r["le_latitude_deg"]), "lon": f(r["le_longitude_deg"]),
                     "elevationM": round(le_e * FT, 1) if le_e is not None else None,
                     "headingTrueDeg": f(r["le_heading_degT"])},
                    {"ident": r["he_ident"], "lat": f(r["he_latitude_deg"]), "lon": f(r["he_longitude_deg"]),
                     "elevationM": round(he_e * FT, 1) if he_e is not None else None,
                     "headingTrueDeg": f(r["he_heading_degT"])}]})
        out.append({**{k: v for k, v in b.items() if k not in ("phase1",)},
                    "lat": f(ap_["latitude_deg"]), "lon": f(ap_["longitude_deg"]),
                    "elevationM": round(elev * FT, 1) if elev is not None else None,
                    "runways": runways,
                    "layoutFidelity": "schematic: runway thresholds from OurAirports; no taxiways/aprons/buildings modelled",
                    "sources": ["src_ourairports"],
                    "inPhase1Region": bool(b.get("phase1")) or b["id"] in ("nevatim", "hatzerim"),
                    "phase1Default": bool(b.get("phase1"))})
    doc = {"schemaVersion": 1, "checkedDate": "2026-11-14",
           "notes": "Generated by tools/extract_bases.py from OurAirports (public domain). Elevations: feet in source converted to metres MSL. Missing runway elevations are filled from the DEM at load time.",
           "bases": out}
    json.dump(doc, open(a.out, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"wrote {len(out)} bases, {sum(len(b['runways']) for b in out)} runways")


if __name__ == "__main__":
    main()
